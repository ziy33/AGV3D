// ==== 碼頭卡車「車輛狀態」視覺 ====
// 待入區 / 無此碼   → 不顯示（NA）
// 已進廠           → 顯示，尾門（屁股門）打開
// 已裝完 / 已裝好貨  → 顯示，尾門關閉
// 已放行           → 顯示，尾門關閉＋全車透明淺綠（離場）
function setTruckDoors(truck, mode) {   // mode: 'open' | 'closed'
    if (!truck) return;
    const off = mode === 'closed' ? 0.61 : 1.89;
    for (let i = 0; i < truck.children.length; i++) {
        const ch = truck.children[i];
        if (ch.userData && ch.userData.part === 'door') {
            ch.position.x = (ch.userData.baseX || 0) + (ch.userData.side || 1) * off;
        }
    }
}
function setTruckGhost(truck, on) {   // on=true → 全車透明 + 淺淺淺綠
    if (!truck) return;
    const seen = {};
    for (let i = 0; i < truck.children.length; i++) {
        const ch = truck.children[i];
        if (!ch.material) continue;
        const mats = Array.isArray(ch.material) ? ch.material : [ch.material];
        for (let m = 0; m < mats.length; m++) {
            const mat = mats[m];
            if (seen[mat.uuid]) continue; seen[mat.uuid] = 1;
            if (on) {
                if (mat.userData.__c === undefined) { mat.userData.__c = mat.color.getHex(); mat.userData.__o = mat.opacity; mat.userData.__dw = mat.depthWrite; }
                mat.transparent = true; mat.opacity = 0.22; mat.depthWrite = false; mat.color.setHex(0x9fe8b0);
            } else if (mat.userData.__c !== undefined) {
                mat.color.setHex(mat.userData.__c); mat.opacity = mat.userData.__o; mat.depthWrite = mat.userData.__dw; mat.userData.__c = undefined;
            }
            mat.needsUpdate = true;
        }
    }
}
function setDockTruckState(i, row) {   // row＝該碼頭(ag)對應紀錄；null / 無 plate → 無車
    const truck = dockTrucks[i]; if (!truck) return;
    const status = row ? String(row.status || '').trim() : '';
    const has = !!(row && row.plate);
    if (!has || status.indexOf('待入區') >= 0) { truck.visible = false; return; }   // NA（無車）
    truck.visible = true;
    const isReleased = status.indexOf('已放行') >= 0;
    const isLoaded = status.indexOf('已裝') >= 0;   // 已裝完 / 已裝好貨
    setTruckDoors(truck, (isReleased || isLoaded) ? 'closed' : 'open');   // 已進廠=門開；已裝完/已放行=門關
    setTruckGhost(truck, isReleased);              // 已放行 → 透明淺綠
}

